export const WpsGovernancePlugin = async () => {
  return {
    // ── 执行后钩子：输出成功后才提交可变状态 ──
    // 回调签名: (input: { tool: string, sessionID: string, callID: string, args: object }, output: { content: array, isError?: boolean }) => Promise<void>
    'tool.execute.after': async (input, output) => {
      const outerTool = input.tool;

      // 与 before 钩子同口径（Issue #382 CR10-1）：网关调用与直连调用归一化。
      {
        const _call = normalizeToolCall(outerTool, input.args);
        if (!_call.toolName) return;

        const toolName = _call.toolName;
        const innerArgs = _call.innerArgs;
        var st = getSessionState(input);

        // ⚠️ Issue #401 W-2（信封单源）：**失败态由各分支自行判定**，不再在入口处对全钩子
        //   `if (output?.isError) return;`——那条早退把「失败事件」整个挡在钩子之外，使失败态
        //   **落进成功态分支的判定**：`toolName:'enableTrackChanges'` 分支据此把
        //   `failedByEnvelope=true` 的事件当成「无 isError ⇒ 成功」，再由 `/已开启/.test(outText)`
        //   （**失败文案本身就含「已开启」**，因为它是「期望开启，回读为关闭」）匹配成功 ⇒
        //   `enabled=true` ⇒ `st.trackChangesOn=true` ⇒ 「修订未生效却放行 replace」。
        //   （实测：失败态下 `trackChangesOn=true`，成功态下亦 `true` —— 二者同值即为失守证据。）
        //   正确初始值本身是 `false`（`createSessionState`），故伤害来自**误判为成功**，非「保持初始值」。
        //   各分支改为「按**结构化失败信号**（isError）或人类可读中文标记」判失败，见下。
        const failedByEnvelope = output?.isError === true;

        if (toolName === 'getActiveDocument') {
          if (failedByEnvelope) return;
          const outText = getOutputText(output);
          if (!outText) return;
          // 输出解析（Issue #395 RC-0′）：同一工具两条通道的**成功体形态不同** ——
          // 内置名（`mcp-server.ts`）返回 **JSON**（`{name,path,paragraphCount,...}`），
          // 注册工具（`content.ts`）返回**文本**（`路径：/总段数：`）。只认文本会让内置名
          // 「名字归一了、内容仍解析不到」⇒ `totalParagraphs=0` ⇒ P2 判据失效。
          // 故**先试 JSON、失败回落文本**，两者取同一组字段（单一解析、不写两套）。
          const docObj = extractJsonFromOutput(outText);
          const paraCountFromJson =
            docObj && typeof docObj.paragraphCount === 'number' ? docObj.paragraphCount : 0;
          // 解析文档路径，检测文档切换：同一会话校对多个文档时，若切换而状态未重置，
          // P1/P2 会基于上一文档的批次进度误拦截。
          const docPathMatch = outText.match(/路径[：:]/i)
            ? outText.match(/路径[：:]\s*(.+)/i)
            : null;
          const currentDocPath = docObj
            ? String(docObj.path || '')
            : docPathMatch
              ? docPathMatch[1].trim()
              : '';
          const docSwitched =
            !!st.activeDocPath && !!currentDocPath && currentDocPath !== st.activeDocPath;
          // 同一文档想重新从头校对时，AI 传 _restart:true 显式完整重置批次进度。
          const restartRequested = innerArgs._restart === true || innerArgs.restart === true;
          if (docSwitched || restartRequested) {
            resetProofreadState(st);
          }
          st.activeDocPath = currentDocPath;
          st.docInfoFetched = true;
          const _wordSlot = appReadStateSlot('word');
          st.appReadState[_wordSlot.appType][_wordSlot.readField] = true;
          const paraMatch =
            outText.match(/总段数[：:]\s*(\d+)/i) || outText.match(/[Pp]aragraphs?[:\s]+(\d+)/i);
          st.totalParagraphs = paraCountFromJson || (paraMatch ? parseInt(paraMatch[1], 10) : 0);
          st.templateFilling.active = false;
          st.templateFilling.docFetched = true;
          st.templateFilling.paragraphsFetched = false;
          st.templateFilling.trackChangesEnabled = false;
          st.templateFilling.userConfirmed = false;
          st.templateFilling.fillKeywords = [];
          st.templateFilling.fillHistory = [];
          st.templateFilling.fieldsFilled = 0;
          return;
        }

        // ⚠️ Issue #399：Excel/PPT 的置位**必须**与 Word 同构 —— 经 appReadStateSlot 取
        // 字段名（不得再写字面量），否则会再次出现「读取侧/写入侧字段名不一致 ⇒ 恒拦」。
        // ⚠️ Issue #401：信封失败事件（`output.isError`）一律不置「已读」标记 —— 与 Word 分支同口径。
        if (toolName === 'getActiveWorkbook' || toolName === 'getActivePresentation') {
          if (failedByEnvelope) return;
          const outText = getOutputText(output);
          if (!outText) return;
          const slot = appReadStateSlot(toolName === 'getActiveWorkbook' ? 'excel' : 'ppt');
          st.appReadState[slot.appType][slot.readField] = true;
          return;
        }

        if (toolName === 'getDocumentParagraphs') {
          if (failedByEnvelope) return;
          const outText = getOutputText(output);
          if (!outText) return;
          const ranges = parseParagraphRanges(outText);
          if (ranges.length === 0) return;
          // 批次边界以「请求参数」为准（输出可能被 MCP 截断，截断处不可信）。
          const requestedStart = Number(innerArgs.start_paragraph);
          const requestedEnd = Number(innerArgs.end_paragraph);
          const hasReqStart = Number.isInteger(requestedStart) && requestedStart >= 1;
          const hasReqEnd = Number.isInteger(requestedEnd) && requestedEnd >= requestedStart;
          // getActiveDocument 输出「总段数: 未知」时从本输出的「共N段」兜底提取总段数。
          if (!st.totalParagraphs) {
            const totalMatch = outText.match(/共(\d+)段/i);
            if (totalMatch) {
              st.totalParagraphs = parseInt(totalMatch[1], 10);
            }
          }
          const rangeEndIdx = ranges[ranges.length - 1].index;
          // 本批逻辑末段：total 已知时按文档实际末段 clamp（请求超界不算截断）。
          const lastIndex =
            hasReqEnd && st.totalParagraphs > 0
              ? Math.min(requestedEnd, st.totalParagraphs)
              : hasReqEnd
                ? requestedEnd
                : rangeEndIdx;
          st.lastBatchParaIndex = lastIndex;
          st.batchActualEndParaIndex = rangeEndIdx;
          st.batchActualStartParaIndex = ranges[0].index;
          st.batchStartParaIndex = ranges[0].index;
          st.batchStarted = true;
          st.batchStartOffset = ranges[0].start;
          // 本批文本不完整而重试同批补齐）。
          const endParaForLast = ranges.find(function (r) {
            return r.index === lastIndex;
          });
          st.batchEndOffset = endParaForLast ? endParaForLast.end : ranges[ranges.length - 1].end;
          st.batchRequestedStart = hasReqStart ? requestedStart : ranges[0].index;
          st.batchRequestedEnd = hasReqEnd ? requestedEnd : rangeEndIdx;
          // 段落原文缓存**按批**保留（不跨批累积）：唯一性判定只对「本批 issue 所在段」有意义，
          // 跨批累积既无用又会让治理状态单调膨胀。必须在本批缓存之前重置。
          st.paragraphTexts = {};
          // 解析 `[idx] (style) [start-end] text` 行（与 content.ts 渲染格式同源），
          // **逐行 + 行首锚定**：多行贪婪匹配会在「段行无尾随文本」时把下一段行吞成本段文本。
          // 同时剥掉展示用的截断标记 —— 标记文本会被误数成 findText 的又一次出现。
          const lineRe = /^\[(\d+)\]\s+\(([^)]*)\)\s+\[(\d+)-(\d+)\](?:\s(.*))?$/;
          for (const rawLine of String(outText).split('\n')) {
            const mm = lineRe.exec(rawLine);
            if (!mm) continue;
            const idx = parseInt(mm[1], 10);
            // 段行**存在**时即使文本为空也写入 ''（区别于「段行不存在」，缺失判定据键是否存在）。
            if (idx >= 1) st.paragraphTexts[idx] = stripTruncationMark(mm[5] || '');
          }
          st.proofreadCalledThisBatch = false;
          st.batchAccumulatedThisBatch = false;
          st.aiProofreadDoneThisBatch = false;
          st.replaceCalledThisBatch = false;
          st.replaceCountThisBatch = 0;
          st.proofreadHadIssues = null;
          st.proofreadIssueOriginals = [];
          st.proofreadIssueEntries = [];
          st.templateFilling.paragraphsFetched = true;
          return;
        }

        if (toolName === 'enableTrackChanges') {
          // R1-3（第 1 轮评审）：失败态判定**先于** `outText` 早退 —— 否则「isError:true 且 content[] 为空」
          // 会在读到 failedByEnvelope 之前返回。
          // ⚠️ R2-1（第 2 轮评审）：失败时**只允许「开启失败 ⇒ 置 false」**，不得对「关闭失败」也置 false：
          //   `enable:false` 失败意味着**修订很可能仍开启**（回读为开启）⇒ 置 false 会让后续 replace
          //   被 P2 拦成**假红**（实测探针：关闭失败 → replace 被修订门禁拦）。
          //   故置位值 = 「本次是否要求开启」：开启失败 ⇒ false（未生效）；关闭失败 ⇒ 维持 true（仍开启）。
          // ⚠️ R2-3（第 2 轮复评）：**缺省 enable 必须按「请求开启」处理** ——
          //   handler 语义是 `enable === true` 才开，但 schema 声明的默认值是 `true`；
          //   若 AI 不传 `enable`（走默认），`innerArgs.enable` 为 `undefined` ⇒ 会被判成
          //   「关闭失败 ⇒ 维持 true」= 放行（**假绿**，实测复现）。缺省须按「开启」处理。
          if (failedByEnvelope) {
            const wantEnable = !(innerArgs.enable === false); // 仅显式 false 才算「请求关闭」
            st.trackChangesOn = !wantEnable;
            st.templateFilling.trackChangesEnabled = st.trackChangesOn;
            return;
          }
          const outText = getOutputText(output);
          if (!outText) return;
          // 失败态 = 结构化信号（isError）**或**人类可读中文标记；二者都不排除「已开启」文案。
          // ⚠️ Issue #395 评审 CR6-1 + CR8-1：**唯一信息源 = handler 的结构化结果**，不得只看入参，
          // 也不得只靠**文案匹配**（后者把治理层耦合到 handler 的措辞 —— 铁律 24 第 2 维「跨模块只过契约」）。
          // ⚠️ Issue #401 W-2（信封单源）：**只有 `isError` 能跨「TS 类型 → mcp-server 投影 → 运行时
          // after 入参」三层存活**。原主判据 `output.success !== false` 读的键在
          // `mcp-server.ts` 投影（`{ content, isError: !result.success }`）中已被**剥离**
          // ⇒ 运行时恒 undefined ⇒ 该判据恒真（**假绿**）。同一信封上仍可用的另两个信号：
          //   ① `output.isError === true`（投影后唯一与 TS 契约键名一致的失败信号）；
          //   ② outText 内的**人类可读中文标记**（`failResult` 的文案，经 `content[]` 透传）。
          // 出现 RC-3 失败态时二者**同时**成立 ⇒ 主判据 + 兜底；二者任一说失败即判未开启。
          const failedByText = /未生效|读取失败|设置修订模式失败/.test(outText);
          const enabled =
            output && output.isError !== true && !failedByText && /已开启/.test(outText);
          st.trackChangesOn = enabled;
          st.templateFilling.trackChangesEnabled = enabled;
          return;
        }

        if (toolName === 'proofreadBasic') {
          if (failedByEnvelope) return;
          const outText = getOutputText(output);
          if (!outText) return;
          st.proofreadCalledThisBatch = true;
          st.aiProofreadDoneThisBatch = false;
          st.replaceCalledThisBatch = false;
          st.replaceCountThisBatch = 0;
          // 三态化：null=解析失败（未知），false=确实无问题，true=确实有问题。
          st.proofreadHadIssues = null;
          st.proofreadIssueOriginals = [];
          st.proofreadIssueEntries = [];
          const parsed = extractJsonFromOutput(outText);
          if (parsed && Array.isArray(parsed.issues)) {
            st.proofreadHadIssues = parsed.issues.length > 0;
            st.proofreadIssueOriginals = parsed.issues.map(i => i.original).filter(Boolean);
            st.proofreadIssueEntries = parsed.issues
              .filter(i => i && i.original)
              .map(i => ({
                original: i.original,
                offset: typeof i.offset === 'number' ? i.offset : null,
                length: typeof i.length === 'number' ? i.length : null,
                paragraphIndex: typeof i.paragraphIndex === 'number' ? i.paragraphIndex : null,
              }));
          }
          return;
        }

        if (toolName === 'replaceInParagraph') {
          if (failedByEnvelope) return;
          st.replaceCalledThisBatch = true;
          st.replaceCountThisBatch++;
          return;
        }

        if (toolName === 'confirmBatchAiProofread') {
          if (failedByEnvelope) return;
          st.aiProofreadDoneThisBatch = true;
          return;
        }

        // 本批已上报（Issue #395 RC-2）：P2「覆盖全文」门禁的前置条件，见 createSessionState 注释。
        if (toolName === 'proofreadAccumulate') {
          if (failedByEnvelope) return;
          st.batchAccumulatedThisBatch = true;
          return;
        }

        // P2：记录服务端报告生成「成功」状态，供 write 拦截规则区分
        // 「合法落盘服务端报告」与「AI 手动 write 伪造报告」。
        // 必须区分成功与失败（如未找到会话/落盘失败），否则 AI 在报告失败后仍可 write 伪造。
        if (toolName === 'generateProofreadReport') {
          const outText = getOutputText(output);
          // ⚠️ Issue #401 W-2：原标记表含 `'success:false'` —— 把 **handler 字段名**当文案兜底，
          // 而在投影后的信封里该键已被剥离、`content[]` 里也不存在该字面量 ⇒ 是**死标记**
          // （永不命中的兜底 = 假绿）。唯一保留的人类可读中文失败标记如下（全部来自 `failResult` 文案）。
          const failureMarkers = [
            '未找到会话',
            '写入文件失败',
            '落盘失败',
            '生成报告失败',
            '写文件失败',
          ];
          const hasFailureMarker = failureMarkers.some(m => outText.indexOf(m) !== -1);
          // 主判据 = `isError`（同 enableTrackChanges 分支的单一信封口径；`success` 键此处已被投影剥离）。
          const ok = output && output.isError !== true && !hasFailureMarker;
          st.reportGenerated = !!ok;
          return;
        }

        if (toolName === 'smartFillField') {
          st.templateFilling.active = true;
          st.templateFilling.fieldsFilled++;
          const keyword = innerArgs.keyword;
          const value = innerArgs.value;
          if (keyword) {
            st.templateFilling.fillKeywords.push(keyword);
          }
          if (keyword && value !== undefined) {
            st.templateFilling.fillHistory.push({ keyword, value, underline: true });
          }
          if (innerArgs._field_mapping_confirmed) {
            st.templateFilling.userConfirmed = true;
          }
          return;
        }

        if (toolName === 'replaceBookmarkContent') {
          st.templateFilling.active = true;
          st.templateFilling.fieldsFilled++;
          if (innerArgs.keyword) {
            st.templateFilling.fillKeywords.push(innerArgs.keyword);
          }
          if (innerArgs.keyword && innerArgs.value !== undefined) {
            st.templateFilling.fillHistory.push({
              keyword: innerArgs.keyword,
              value: innerArgs.value,
              underline: true,
            });
          }
          return;
        }
      }
    },

    // ── 执行前钩子：所有规则校验 ──
    // 回调签名（官方 @opencode-ai/plugin）：(input: { tool, sessionID, callID }, output: { args }) => Promise<void>
    // ⚠️ Issue #395 RC-6：官方契约里 before 的参数在**第二个参数 output.args**（after 才在 input.args）——
    //   原实现读 input.args 与契约相反，导致真实运行时 innerArgs 恒为 {}：校对门禁永不可满足（假红死锁），
    //   且 P2「禁止手写伪造校对报告」静默失守（假绿）。参数来源**单一归一**为本函数，3 个消费点共用。
    // rules: G1-G7 通用规则, P1-P4 校对规则, T1-T11 模板填写规则
    'tool.execute.before': async (input, output) => {
      const outerTool = input.tool;
      // 参数来源唯一归一：官方 output.args 优先，`||` 回落旧契约 input.args（兼容既有调用形态）。
      const beforeArgs = () => (output && output.args) || (input && input.args) || {};

      // ==================== 规则 G2：wps_execute_method 白名单 ====================
      if (outerTool === 'wps-office_wps_execute_method' || outerTool === 'wps_execute_method') {
        const args = beforeArgs();
        // Issue #382：`method` 可能被放在 `params` 里（实测 AI 传 `method:"enableTrackChanges"` 时消息里是空串，
        // 诊断价值为 0）—— 取值兼容两种形状，并**回显键名**便于自纠。
        const method = args.method || (args.params && args.params.method) || '';
        const allowed = Array.from(EXECUTE_METHOD_WHITELIST).some(a => method.startsWith(a));
        if (!allowed) {
          throw enhanceBlock(
            getSessionState(input),
            `【执行治理】wps_execute_method 只允许白名单 API。` +
              `当前 method="${method}" 不在白名单中。` +
              `允许的 API：${Array.from(EXECUTE_METHOD_WHITELIST).join(', ')}。` +
              `其他操作请通过 wps_office_execute 使用已注册工具。` +
              `（本次调用参数键：${Object.keys(args).join(', ') || '（无）'}）`,
            'G2',
            outerTool
          );
        }
      }

      // ── 规则 P2（原生 write 分支）：禁止 AI 手动 write 伪造校对报告 ──
      // 真实会话中 AI 在 generateProofreadReport 失败后，直接用 OpenCode 原生 write/edit 工具
      // 手动构造 Markdown 报告写入目标路径，绕过服务端真实累计的数据。原生 write（outerTool='write'）
      // 在下方「非网关调用直接 return」闸门处会被放行，故此处必须在闸门之前拦截。
      const isReportPath = pathStr =>
        typeof pathStr === 'string' && pathStr.indexOf('校对报告') !== -1;
      const NATIVE_WRITE_TOOLS = ['write', 'writeText', 'writeFile', 'edit'];
      if (NATIVE_WRITE_TOOLS.indexOf(outerTool) !== -1) {
        const nativeArgs = beforeArgs();
        const nativePath =
          nativeArgs.path || nativeArgs.filePath || nativeArgs.file_path || nativeArgs.file;
        const st = getSessionState(input);
        if (isReportPath(nativePath) && !st.reportGenerated) {
          throw enhanceBlock(
            st,
            `【执行治理】【P2】检测到直接写入“校对报告”路径（${nativePath}），但服务端尚未成功生成报告。\n` +
              `校对报告必须由服务端真实累计的数据生成，禁止 AI 手动 write 伪造报告。\n` +
              `请先调用 generateProofreadReport（走 wps_office_execute 网关，传 session_id + output_file）\n` +
              `由服务端生成并落盘；若需自行落盘，请用其返回的 content 文本（不得手动构造报告体）。`,
            'P2',
            outerTool
          );
        }
      }

      // 以下规则对「网关调用」与「直连工具调用」**同一口径**（Issue #382 CR10-1：归一化单点）。
      const _call = normalizeToolCall(outerTool, beforeArgs());
      if (!_call.toolName) return; // 非工具调用（如内置 wps_check_connection / 原生工具）不参与 P/T 规则
      const toolName = _call.toolName;
      const innerArgs = _call.innerArgs;
      var st = getSessionState(input);

      // ==================== 规则 G5：文件路径安全检查 ====================
      checkFilePathSafety(innerArgs);

      // ==================== 规则 G6：密码参数保护 ====================
      checkPasswordProtection(toolName, innerArgs);

      // ==================== 规则 G3：读前必写 ====================
      if (requiresReadBeforeWrite(toolName)) {
        // ⚠️ Issue #399 评审 R3-🟡F：app 归属**只取权威来源**（归一化取出的 `app` / COM_ACTION_APP 表），
        //   **不得**读调用参数 `innerArgs.appType` —— 那是**第二份 app 真值**，可被注入 ⇒ 跨 app 绕过。
        const appType = getAppType(toolName, _call.app);
        // ⚠️ Issue #399 评审 R4-🟡G：`common`（跨 app 共用工具，如 save / saveAs / convertFormat）对 app
        //   无归属 ⇒ 任一 app 已读即满足「读前必写」（否则在 Excel/PPT 上下文会被误要求读 Word —— 与本次
        //   Issue 同类的误拦）。其它 app 仍严格查**本 app** 的标记。
        const hasRead = a =>
          !!(st.appReadState[a] && st.appReadState[a][appReadStateSlot(a).readField]);
        const appReadOk =
          appType === 'common' ? ['word', 'excel', 'ppt'].some(hasRead) : hasRead(appType);
        if (!appReadOk) {
          // 报错指向**当前 app 对应的那个读取工具**（原文案一律列出三个，Excel 用户会照着
          // 「getActiveDocument(Word)」去调，进一步放大困惑）；common 文案提示任一 app 读取工具。
          const readerOf = {
            word: 'getActiveDocument',
            excel: 'getActiveWorkbook',
            ppt: 'getActivePresentation',
            common: 'getActiveDocument / getActiveWorkbook / getActivePresentation',
          };
          throw enhanceBlock(
            st,
            `【执行治理】执行 ${toolName} 前必须先读取文档状态。` +
              `请先调用 ${readerOf[appType] || 'getActiveDocument'} 了解当前文档信息。`,
            'G3',
            toolName
          );
        }
      }

      // ==================== 规则 G4：破坏性操作确认 ====================
      if (DESTRUCTIVE_TOOLS.has(toolName)) {
        const confirm = innerArgs.confirm;
        if (confirm !== true) {
          throw enhanceBlock(
            st,
            `【执行治理】${toolName} 是破坏性操作，必须传递 confirm: true 确认。` +
              `请在调用参数中添加 arguments: { ..., confirm: true } 以确认此操作。`,
            'G4',
            toolName
          );
        }
      }

      // ==================== 规则 G7：参数范围校验 ====================
      checkParamRange(toolName, innerArgs);

      // ── 规则 P2（网关 writeFile 分支）：禁止 AI 手动 write 伪造校对报告 ──
      const reportPathArg = innerArgs.filePath || innerArgs.path || innerArgs.file_path;
      if (
        (toolName === 'writeFile' || toolName === 'write' || toolName === 'writeText') &&
        isReportPath(reportPathArg) &&
        !st.reportGenerated
      ) {
        throw enhanceBlock(
          st,
          `【执行治理】【P2】检测到直接写入“校对报告”路径（${reportPathArg}），但服务端尚未成功生成报告。\n` +
            `校对报告必须由服务端真实累计的数据生成，禁止 AI 手动 write 伪造报告。\n` +
            `请先调用 generateProofreadReport（走 wps_office_execute 网关，传 session_id + output_file）\n` +
            `由服务端生成并落盘；若需自行落盘，请用其返回的 content 文本（不得手动构造报告体）。`,
          'P2',
          outerTool
        );
      }

      if (toolName === 'getActiveDocument' || toolName === 'enableTrackChanges') {
        return;
      }

      // ── 规则 P2：覆盖全文后强制生成收尾报告 ──
      // 真实会话中 AI 空上报到文档总段数（覆盖全文）后未调用 generateProofreadReport 就直接结束，
      // 用户拿到的只是 AI 编造的内容而非服务端真实报告。服务端只在报告工具处做覆盖门禁，
      // 它不知道「AI 是否还要继续推进」——此处用同一会话已取回的段落边界判定进度已达全文，
      // 拦下继续推进、强制收尾。
      // 判据（本批实际返回末段，服务端不具备）：本批取回末段已达文档总段数，且**本批已上报**
      // （Issue #395 RC-2 前置），且服务端尚未出报告。
      //   · 「本批已上报」前置为何必需：单批文档首批取段即「覆盖全文」，若不看本批是否走完，
      //     ③取文本/④校对/⑤确认/⑥替换会在校对开始前被整体拦下（只剩 accumulate/report 放行），
      //     而报告门禁又要求先有校对痕迹 ⇒ 闭环死锁。加此条后「覆盖全文」语义收敛为
      //     「本批走完且已达文档末尾」，多批文档末批上报后继续推进**仍被拦**（AC3.2）。
      // 不拦截 proofreadAccumulate（覆盖全文正是通过它上报）、generateProofreadReport（收尾本身）、
      // getTrackChangesStatus / save（收尾/保存类操作）。
      if (
        PROOFREAD_ADVANCE_TOOLS.indexOf(toolName) !== -1 &&
        !st.reportGenerated &&
        st.batchAccumulatedThisBatch &&
        st.totalParagraphs > 0 &&
        st.batchActualEndParaIndex >= st.totalParagraphs
      ) {
        throw enhanceBlock(
          st,
          `【执行治理】【P2】文档已覆盖全文（取回至段落 ${st.batchActualEndParaIndex}/${st.totalParagraphs}），` +
            `但尚未调用 generateProofreadReport 生成收尾报告。\n` +
            `覆盖全文后必须调用 generateProofreadReport（走 wps_office_execute 网关，传 session_id + output_file）\n` +
            `生成服务端真实累计数据的六维报告，禁止继续推进校对流程。`,
          'P2',
          outerTool
        );
      }

      // ── 规则 P1 + P2 + P4：getDocumentParagraphs ──
      if (toolName === 'getDocumentParagraphs') {
        const batchStartArg = Number(innerArgs.start_paragraph) || 1;
        const batchEndArg = Number(innerArgs.end_paragraph) || batchStartArg + 199;
        const retryingSameBatch =
          st.batchRequestedStart != null &&
          batchStartArg === st.batchRequestedStart &&
          batchEndArg === st.batchRequestedEnd;
        // Issue #420：**本批已取过区间内的重读**放行 —— 取段落是**只读**操作，不推进任何进度、
        // 不可能跳过内容，却会被下面「本批未走完不得取下一批」整片拦死（会话实证：AI 只需回看
        // 段 19-27 核对坐标，被 P1 拦后被迫改道做偏移取证，浪费十余轮）。
        // 判据：请求区间完全落在**已取段上界**内（`end ≤ lastBatchParaIndex`；该值 = 上次请求的
        // 逻辑末段而非「已校对」末段，故本豁免的准确语义是「只读重取已到过的范围」）。
        const rereadingCoveredRange =
          st.lastBatchParaIndex > 0 && batchEndArg <= st.lastBatchParaIndex;
        // P1：本批未走完（未校对 / 未确认 / 有问题未修复）不得取下一批
        if (st.batchStarted && !retryingSameBatch && !rereadingCoveredRange) {
          if (!st.proofreadCalledThisBatch) {
            throw enhanceBlock(
              st,
              `【执行治理】【P1】当前批（段落 ${st.batchStartParaIndex}-${st.lastBatchParaIndex}）` +
                `尚未调用 proofreadBasic，不得获取下一批。\n` +
                `每批必须先调 proofreadBasic 进行基础校对（肉眼扫不算校对），禁止仅凭视觉判断跳过。` +
                `\n唯一例外：整块跳过（本批每段均为表格单元格且无正文叙述句）须先按 SKILL 铁律 2 上报。\n` +
                `如需重新开始，请先调用 getActiveDocument 传 _restart: true 重置进度。`,
              'P1',
              'getDocumentParagraphs'
            );
          }
          if (!st.aiProofreadDoneThisBatch) {
            throw enhanceBlock(
              st,
              `【执行治理】【P1】当前批的 AI 智能校对尚未确认。` +
                `调完 proofreadBasic 后必须调用 confirmBatchAiProofread 确认 AI 校对完成，再获取下一批。`,
              'P1',
              'getDocumentParagraphs'
            );
          }
          if (st.proofreadHadIssues === true && !st.replaceCalledThisBatch) {
            throw enhanceBlock(
              st,
              `【执行治理】【P1】当前批（段落 ${st.batchStartParaIndex}-${st.lastBatchParaIndex}）` +
                `的校对问题尚未修复，不得获取下一批。\n` +
                `请先调用 replaceInParagraph 完成本批修复（或确认这些条目为 report_only）。`,
              'P1',
              'getDocumentParagraphs'
            );
          }
        }
        if (!st.docInfoFetched) {
          throw enhanceBlock(
            st,
            `【执行治理】请先调用 getActiveDocument 了解文档总段落数，` + `再获取段落列表。`,
            'P2',
            'getDocumentParagraphs'
          );
        }
        if (batchStartArg < 1) {
          throw new Error(`【执行治理】start_paragraph 必须 ≥ 1（当前值: ${batchStartArg}）。`);
        }
        if (batchEndArg < batchStartArg) {
          throw new Error(
            `【执行治理】end_paragraph（${batchEndArg}）必须 ≥ start_paragraph（${batchStartArg}）。`
          );
        }
        const count = batchEndArg - batchStartArg + 1;
        if (count > MAX_PARAGRAPHS_PER_BATCH) {
          throw new Error(
            `【执行治理】getDocumentParagraphs 单次请求 ${count} 段，` +
              `超过上限 ${MAX_PARAGRAPHS_PER_BATCH} 段。请分多次获取。`
          );
        }
        // P1：首批必须从第 1 段开始
        if (st.lastBatchParaIndex === 0 && batchStartArg !== 1) {
          throw new Error(
            `【执行治理】首次 getDocumentParagraphs 必须从第 1 段开始（当前 start=${batchStartArg}）。`
          );
        }
        // P1：批次连续（或从第 1 段重新开始）。同批重试（相同 start/end）放行，
        // 否则 proofreadBasic 失败后重取本批会被拦死（唯一出路只剩 getActiveDocument 重置，丢失进度）。
        if (
          st.lastBatchParaIndex > 0 &&
          batchStartArg !== st.lastBatchParaIndex + 1 &&
          !retryingSameBatch &&
          !rereadingCoveredRange &&
          batchStartArg !== 1
        ) {
          throw enhanceBlock(
            st,
            `【执行治理】【P1】批次不连续：上一批结束于段落 ${st.lastBatchParaIndex}，` +
              `当前批从段落 ${batchStartArg} 开始。\n` +
              `批次必须严格连续（从段落 ${st.lastBatchParaIndex + 1} 继续），或从第 1 段重新开始` +
              `（重新开始请先调用 getActiveDocument 传 _restart: true）。`,
            'P1',
            'getDocumentParagraphs'
          );
        }
        return;
      }

      // ── 规则 P1 + P2：proofreadBasic ──
      if (toolName === 'proofreadBasic') {
        if (!st.docInfoFetched) {
          throw enhanceBlock(
            st,
            `【执行治理】请先调用 getActiveDocument 了解文档总段落数，` +
              `输出分批校对计划后，再开始校对。`,
            'P2',
            toolName
          );
        }
        if (!st.batchStarted) {
          throw enhanceBlock(
            st,
            `【执行治理】请先调用 getDocumentParagraphs 获取第一批段落，` +
              `确认分批计划后再调 proofreadBasic。`,
            'P1',
            toolName
          );
        }
        const so = normalizeStartOffset(innerArgs);
        if (so === undefined || so === null) {
          throw new Error(
            `【执行治理】proofreadBasic 缺少 startOffset 参数。` +
              `必须传入本批第一段的字符起始位置。`
          );
        }
        if (st.proofreadCalledThisBatch) {
          throw new Error(
            `【执行治理】本批已调过 proofreadBasic，禁止再次调用。` + `每批只准调 1 次。`
          );
        }
        if (st.batchStartOffset !== null && so !== st.batchStartOffset) {
          throw new Error(
            `【执行治理】proofreadBasic startOffset=${so} 与本批第一段起始位置 ` +
              `${st.batchStartOffset} 不匹配。`
          );
        }
        // P2：文本必须来自本批 getDocumentTextByRange，禁止一次性传多批。
        if (!innerArgs.file_path && st.batchEndOffset !== null) {
          const text = innerArgs.text || '';
          if (text.length === 0) {
            throw new Error(
              `【执行治理】proofreadBasic 传入文本为空。` +
                `请用 getDocumentTextByRange(startOffset=${so}, length=${st.batchEndOffset - so}) 获取文本。`
            );
          }
          if (text.length < 20) {
            throw new Error(
              `【执行治理】proofreadBasic 传入文本仅 ${text.length} 字符，` +
                `明显不足（预期约 ${st.batchEndOffset - so} 字符）。`
            );
          }
          const expectedLen = st.batchEndOffset - st.batchStartOffset;
          const maxLen = Math.max(expectedLen * 2, MAX_DOC_TEXT_BYTES);
          if (text.length > maxLen) {
            throw enhanceBlock(
              st,
              `【执行治理】【P2】proofreadBasic 传入文本 ${text.length} 字符 ` +
                `远超本批预期范围 ${expectedLen} 字符。` +
                `禁止一次性校对多批。请严格每批 ≤${MAX_PARAGRAPHS_PER_BATCH} 段、单次 proofreadBasic 只传本批文本。`,
              'P2',
              toolName
            );
          }
        }
        return;
      }

      // ── 规则 P2：getDocumentTextByRange 不得越过本批范围 ──
      // PS 侧（wps-com.ps1）缺省 length 时取 `doc.Content.End - startOffset` = 文档剩余全文，
      // 故「只传 start_offset、不传 length」即可无限拉全文，必须与显式 length 同判。
      if (toolName === 'getDocumentTextByRange') {
        const requestedLen = innerArgs.length;
        const reqStart = normalizeStartOffset(innerArgs);
        const reqLen = Number(requestedLen);
        const batchStart = st.batchStartOffset;
        const batchEnd = st.batchEndOffset;
        const lenCap =
          batchStart !== null && batchEnd !== null
            ? Math.max((batchEnd - batchStart) * 2, MAX_DOC_TEXT_BYTES)
            : MAX_DOC_TEXT_BYTES;
        // 起点越界：本批边界已登记时按本批终点，否则按整篇上限兜底
        const startCap = batchEnd === null ? lenCap : batchEnd;
        const explicitOver = Number.isFinite(reqLen) && reqLen > lenCap;
        // 缺省 length：本批边界尚未登记时按整篇上限兜底（缺省即拉到文档尾，越过上限即拦）
        const missingLenBypass = !Number.isFinite(reqLen) && batchEnd === null;
        if (
          (Number.isFinite(reqStart) && reqStart > startCap) ||
          explicitOver ||
          missingLenBypass
        ) {
          throw enhanceBlock(
            st,
            `【执行治理】【P2】getDocumentTextByRange start_offset=${normalizeStartOffset(innerArgs) ?? '未传'} length=${requestedLen ?? '未传'} 越过本批范围` +
              `（上限 ${lenCap} 字符，约 ${MAX_PARAGRAPHS_PER_BATCH} 段）。` +
              `禁止一次性拉取多批文本。请只获取本批范围内的文本；必须显式传 length 且 ≤ 本批剩余。`,
            'P2',
            toolName
          );
        }
        return;
      }

      // ── 规则 P1：confirmBatchAiProofread 必须在 proofreadBasic 之后 ──
      if (toolName === 'confirmBatchAiProofread') {
        if (st.batchStarted && !st.proofreadCalledThisBatch) {
          throw enhanceBlock(
            st,
            `【执行治理】【P1】confirmBatchAiProofread 必须在 proofreadBasic 之后调用。\n` +
              `当前批尚未进行基础校对，请先调用 proofreadBasic。` +
              `（禁止跳过基础校对直接确认 AI 校对）`,
            'P1',
            toolName
          );
        }
        return;
      }

      // ── 规则 P4：proofreadAccumulate 上报真实进度 ──
      // 服务端 checkProgressGate 已强制「超界 / 回退重复 / 单批增量超限」；此处只校验
      // 服务端**看不到**的那部分真值：本会话实际取回了哪几段（batchActualStart/End）。
      if (toolName === 'proofreadAccumulate') {
        const issuesArg = innerArgs.issues;
        const actualEndParaIndex = st.batchActualEndParaIndex || st.lastBatchParaIndex || 0;
        // P4-a：进度不得超本批实际取回末段（假进度）
        if (
          typeof innerArgs._processed_to_paragraph === 'number' &&
          actualEndParaIndex > 0 &&
          innerArgs._processed_to_paragraph > actualEndParaIndex
        ) {
          throw enhanceBlock(
            st,
            `【执行治理】【P4】_processed_to_paragraph=${innerArgs._processed_to_paragraph} ` +
              `超过本批实际获取到的段落 ${actualEndParaIndex}。\n` +
              `你尚未通过 getDocumentParagraphs 获取到段落 ${innerArgs._processed_to_paragraph}，` +
              `不能宣称已校对到该段落（假进度）。请逐批真实获取并校对，本批进度应 ≤ ${actualEndParaIndex}。`,
            'P4',
            toolName
          );
        }
        // P4-b：issues 必须属于本批窗口（防复用其它批次的陈旧 issue 填充伪装进度）
        if (Array.isArray(issuesArg) && issuesArg.length > 0 && actualEndParaIndex > 0) {
          const winStart =
            st.batchActualStartParaIndex > 0
              ? st.batchActualStartParaIndex
              : st.batchRequestedStart || actualEndParaIndex;
          for (const it of issuesArg) {
            const pid =
              it &&
              (typeof it.paragraphIndex === 'number'
                ? it.paragraphIndex
                : typeof it.paragraph_index === 'number'
                  ? it.paragraph_index
                  : undefined);
            if (pid !== undefined && (pid < winStart || pid > actualEndParaIndex)) {
              throw enhanceBlock(
                st,
                `【执行治理】【P4】本批上报的 issue 段落索引 ${pid} 不在当前批窗口 ` +
                  `（段落 ${winStart}..${actualEndParaIndex}）内。\n` +
                  `禁止复用其它批次的陈旧 issue 填充 issues 数组来伪装本批进度。` +
                  `请只上报本批真实发现的校对问题。`,
                'P4',
                toolName
              );
            }
          }
        }
        return;
      }

      // ── 规则 P2 + P3：替换操作 ──
      if (toolName === 'replaceInParagraph' || toolName === 'findReplace') {
        if (!st.trackChangesOn) {
          throw enhanceBlock(
            st,
            `【执行治理】请先调用 enableTrackChanges(true) 开启修订模式，` + `再执行替换操作。`,
            'P2',
            toolName
          );
        }
        if (toolName === 'findReplace') {
          if (st.batchStarted) {
            throw enhanceBlock(
              st,
              `【执行治理】分批校对流程中禁止使用 findReplace（不支持修订标记）。` +
                `请改用 replaceInParagraph。`,
              'P2',
              toolName
            );
          }
          const findTextFR = innerArgs.findText || innerArgs.find || innerArgs.find_text || '';
          const colonMatchFR = findTextFR.match(/^[\u4e00-\u9fff]+[：:]/);
          if (colonMatchFR && findTextFR.length >= 2 && findTextFR.length <= 20) {
            throw new Error(
              `【执行治理·禁止低级替换】检测到用 findReplace 做模板填写。\n` +
                `findText="${findTextFR}" 看起来是一个模板字段标签。\n` +
                `请改用 smartFillField 填写模板字段。`
            );
          }
          return;
        }
        // replaceInParagraph
        const findText = innerArgs.findText || innerArgs.find || innerArgs.find_text || '';
        const colonMatch = findText.match(/^[\u4e00-\u9fff]+[：:]/);
        if (colonMatch && findText.length >= 2 && findText.length <= 20) {
          throw new Error(
            `【执行治理·禁止低级替换】检测到用 replaceInParagraph 做模板填写。\n` +
              `findText="${findText}" 看起来是一个模板字段标签。\n` +
              `请改用 smartFillField 填写模板字段。`
          );
        }
        // 模板填写/修复场景（templateFilling.active）跳过校对流程前置检查
        if (!st.templateFilling.active && st.batchStarted && !st.proofreadCalledThisBatch) {
          throw enhanceBlock(
            st,
            `【执行治理】replaceInParagraph 必须在同一批的 proofreadBasic 之后调用。`,
            'P2',
            toolName
          );
        }
        if (!st.templateFilling.active && st.batchStarted && !st.aiProofreadDoneThisBatch) {
          throw enhanceBlock(
            st,
            `【执行治理】AI 智能校对未完成。请在 proofreadBasic 之后调用 ` +
              `confirmBatchAiProofread 确认 AI 校对已完成，再执行替换操作。`,
            'P2',
            toolName
          );
        }
        // P3：基础校对无 issue 时，禁止 AI 自行大量修复（防编造问题）
        if (
          !st.templateFilling.active &&
          st.batchStarted &&
          st.proofreadHadIssues === false &&
          st.replaceCountThisBatch >= AI_FIXES_NO_ISSUES_LIMIT &&
          !innerArgs._force_ai_fix
        ) {
          throw enhanceBlock(
            st,
            `【执行治理】【P3】基础校对未发现本批存在任何问题，` +
              `AI 已自行修复 ${st.replaceCountThisBatch} 处。\n` +
              `禁止 AI 编造不存在的校对问题。如确认此处确需修复，` +
              `请在参数中添加 _force_ai_fix: true 以强制放行。`,
            'P3',
            toolName
          );
        }
        // P3：交叉校验 — 替换内容应与已知校对 issue 对应（防「把正确的改成错误的」）
        if (
          !st.templateFilling.active &&
          st.batchStarted &&
          st.proofreadHadIssues === true &&
          st.proofreadIssueOriginals.length > 0 &&
          findText &&
          !innerArgs._force_ai_fix
        ) {
          // ① 含截断标记 且 不匹配任何已知 issue.original → 判定为 context 截断展示文本（非原文），
          //    文档中必然不存在，拦截并引导改用 proofreadBasic 返回的 original。
          const hasTruncation = hasTruncationMarker(findText);
          const matchesIssue = st.proofreadIssueOriginals.some(function (orig) {
            return orig && (orig.indexOf(findText) !== -1 || findText.indexOf(orig) !== -1);
          });
          if (hasTruncation && !matchesIssue) {
            throw enhanceBlock(
              st,
              `【执行治理】【P3】replaceInParagraph findText="${findText}" 含截断标记（.../…/……）且不匹配任何已知问题原文，` +
                `该文本在文档中不存在，替换必然失败。\n` +
                `请改用 proofreadBasic / getDocumentParagraphs 返回的完整 original 原文作为 findText，` +
                `不得使用带截断标记的 context 展示文本。如需强制修复请传 _force_ai_fix: true。`,
              'P3',
              toolName
            );
          }
          if (!matchesIssue) {
            const maxShow = 5;
            const shown = st.proofreadIssueOriginals.slice(0, maxShow);
            const more =
              st.proofreadIssueOriginals.length > maxShow
                ? `...等共 ${st.proofreadIssueOriginals.length} 条`
                : '';
            throw enhanceBlock(
              st,
              `【执行治理】【P3】replaceInParagraph findText="${findText}" ` +
                `与 proofreadBasic 找到的任何 issue 原文都不匹配。\n` +
                `已知问题原文：${shown.join('、')}${more}\n` +
                `AI 不应修复基础校对未发现的问题。如需强制修复请传 _force_ai_fix: true。`,
              'P3',
              toolName
            );
          }
          // ② findText 只是某条 issue.original 的真子串（非全等）→ 段内必然多处可匹配，
          //    与 replaceInParagraph 的「段内首次匹配」语义矛盾。
          const candidateOrigins = st.proofreadIssueEntries.filter(function (e) {
            return (
              e.original &&
              (e.original.indexOf(findText) !== -1 || findText.indexOf(e.original) !== -1)
            );
          });
          const substringOnly = candidateOrigins.filter(function (e) {
            return e.original !== findText;
          });
          if (candidateOrigins.length > 0 && substringOnly.length === candidateOrigins.length) {
            throw enhanceBlock(
              st,
              `【执行治理】【P3】replaceInParagraph findText="${findText}" 只是已知问题原文的**子串**（非完整原文），` +
                `段内存在多处可匹配位置，替换落点不确定（replaceInParagraph 按段内首次匹配替换）。\n` +
                `请改用该条 issue 的**完整 original** 作为 findText。如需强制修复请传 _force_ai_fix: true。`,
              'P3',
              toolName
            );
          }
          // ③ 段内唯一性：以段落原文（paragraphTexts，来源 getDocumentParagraphs）计数 ——
          //    「findText 在段内出现几次」无法从 issue 列表自身推出，故必须落一份段文本。
          const paraIdx16 = innerArgs.paragraphIndex;
          if (typeof paraIdx16 === 'number') {
            // 段文本**缺失**时不得静默放行（occ=0 会让唯一性判定形同不存在 = 假绿）。
            const paraKnown =
              st.paragraphTexts &&
              Object.prototype.hasOwnProperty.call(st.paragraphTexts, paraIdx16);
            if (!paraKnown) {
              throw enhanceBlock(
                st,
                `【执行治理】【P3】无法校验段落 ${paraIdx16} 内 findText="${findText}" 的唯一性：` +
                  `本批段落原文缓存中缺少该段（getDocumentParagraphs 输出可能被截断，或该段不在本批返回范围内）。\n` +
                  `缺失段文本时「是否唯一」不可判定 —— 不得默认为唯一（否则按段内首次匹配替换，落点不可预期）。\n` +
                  `请先用相同的 start_paragraph/end_paragraph 重试 getDocumentParagraphs 补齐本批段落，再执行替换。` +
                  `如需强制修复请传 _force_ai_fix: true。`,
                'P3',
                toolName
              );
            }
            const paraText16 = st.paragraphTexts[paraIdx16];
            let occ = 0;
            if (typeof paraText16 === 'string') {
              let i = paraText16.indexOf(findText);
              while (i !== -1) {
                occ++;
                i = paraText16.indexOf(findText, i + findText.length);
              }
            }
            if (occ > 1) {
              throw enhanceBlock(
                st,
                `【执行治理】【P3】replaceInParagraph 段落 ${paraIdx16} 内 findText="${findText}" ` +
                  `出现 ${occ} 次，段内不唯一、替换落点歧义` +
                  `（replaceInParagraph 按段内首次匹配替换，AI 无法预期改到哪一处）。\n` +
                  `请改为段内唯一的完整 original 作为 findText（必要时扩大匹配范围使 findText 唯一）。` +
                  `如需强制修复请传 _force_ai_fix: true。`,
                'P3',
                toolName
              );
            }
            // 段内存在 ≥2 处不同原文都含 findText → 落点歧义
            const distinctOrigins = {};
            for (const e of st.proofreadIssueEntries) {
              if (
                e.paragraphIndex === paraIdx16 &&
                e.original &&
                e.original.indexOf(findText) !== -1
              ) {
                distinctOrigins[e.original] = true;
              }
            }
            if (Object.keys(distinctOrigins).length > 1) {
              throw enhanceBlock(
                st,
                `【执行治理】【P3】replaceInParagraph 段落 ${paraIdx16} 内有 ${Object.keys(distinctOrigins).length} 处` +
                  `不同原文都含 findText="${findText}"，段内不唯一、替换落点歧义。\n` +
                  `请用完整且段内唯一的 original 作为 findText（必要时扩大匹配范围）。如需强制修复请传 _force_ai_fix: true。`,
                'P3',
                toolName
              );
            }
          }
        }
        if (st.batchStarted) {
          const paraIdx = innerArgs.paragraphIndex;
          if (paraIdx !== undefined) {
            if (paraIdx < st.batchStartParaIndex) {
              throw new Error(
                `【执行治理】replaceInParagraph paragraphIndex=${paraIdx} 在本批起始段落 ${st.batchStartParaIndex} 之前。`
              );
            }
            if (paraIdx > st.lastBatchParaIndex) {
              throw new Error(
                `【执行治理】replaceInParagraph paragraphIndex=${paraIdx} 超出本批结束段落 ${st.lastBatchParaIndex}。`
              );
            }
          }
        }
        return;
      }

      // ── 模板填写工作流规则（T1-T11） ──
      if (toolName === 'smartFillField' || toolName === 'replaceBookmarkContent') {
        // T1：评估文档
        if (!st.templateFilling.active && !st.templateFilling.docFetched) {
          throw enhanceBlock(
            st,
            `【执行治理】模板填写前请先评估文档规模。` +
              `请先调用 getActiveDocument 了解文档总段落数。`,
            'T1',
            toolName
          );
        }
        // T2：分批
        if (!st.templateFilling.active && !st.templateFilling.paragraphsFetched) {
          throw enhanceBlock(
            st,
            `【执行治理】模板填写前请先分批。` +
              `请先调用 getDocumentParagraphs 以每批 ≤200 段评估文档结构，再逐批填写。`,
            'T2',
            toolName
          );
        }
        // T7：首次填写前必须输出字段对照表并获用户确认
        if (
          toolName === 'smartFillField' &&
          !st.templateFilling.userConfirmed &&
          !innerArgs._field_mapping_confirmed
        ) {
          throw enhanceBlock(
            st,
            `【执行治理·禁止编造】首次 smartFillField 前，你必须：\n` +
              `1. 列出文档中所有待填写字段与用户提供值的对照表\n` +
              `2. 标记出用户未提供的字段（如缺少"采购项目编号"的值）\n` +
              `3. 要求用户补充缺失值，不得自行编造\n` +
              `4. 用户确认后，在首次 smartFillField 参数中添加 ` +
              `_field_mapping_confirmed: true 即可放行`,
            'T7',
            toolName
          );
        }
        // T3：修订模式
        if (!st.templateFilling.trackChangesEnabled) {
          throw enhanceBlock(
            st,
            `【执行治理】模板填写前请先调用 enableTrackChanges(true) 开启修订模式，` +
              `以便追踪填写变更。`,
            'T3',
            toolName
          );
        }
        // T8：跳过签字字段
        if (innerArgs.keyword) {
          const signaturePatterns = ['签字', '签名', '签章', '盖章'];
          for (var s = 0; s < signaturePatterns.length; s++) {
            if (innerArgs.keyword.indexOf(signaturePatterns[s]) !== -1) {
              throw enhanceBlock(
                st,
                `【执行治理·跳过签字】"${innerArgs.keyword}" 包含"${signaturePatterns[s]}"，` +
                  `属于手工签章字段，不应由AI填写。请跳过此字段。`,
                'T8',
                toolName
              );
            }
          }
        }
        // T6：禁止子串重复填写（可传 _substring_confirmed: true 绕过）
        const newKeyword = innerArgs.keyword;
        if (
          newKeyword &&
          !innerArgs._substring_confirmed &&
          st.templateFilling.fillKeywords.length > 0
        ) {
          for (var k = 0; k < st.templateFilling.fillKeywords.length; k++) {
            const existingKwd = st.templateFilling.fillKeywords[k];
            if (existingKwd.indexOf(newKeyword) !== -1 || newKeyword.indexOf(existingKwd) !== -1) {
              if (existingKwd !== newKeyword) {
                throw enhanceBlock(
                  st,
                  `【执行治理·禁止重复】"${newKeyword}" 与已填写字段 "${existingKwd}" ` +
                    `存在包含关系（子串/超串）。请确认这是否是同一字段：\n` +
                    `- 如果是同一字段（如"包号"是"采购包号"的一部分），不要再次填写\n` +
                    `- 如果是不同字段，请向用户确认后在参数中添加 _substring_confirmed: true 绕过`,
                  'T6',
                  toolName
                );
              }
            }
          }
        }
        return;
      }
    },
  };
};
