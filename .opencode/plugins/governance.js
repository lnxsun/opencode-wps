// 生成规则 key：从拦截消息中提取标签（如 [P1]、[G3]、[T1]）。
function extractRuleKey(message) {
  // 识别半角 [P1] 与全角 【P1】 两种标签（governance 拦截消息两种风格都用）。
  const m = /[\[【]([A-Z]\d+[a-z]?)[\]】]/.exec(message || '');
  if (m) return m[1].replace(/[a-z]$/, '');
  return '';
}

// 统一增强入口：拦截 Error 构造时调用。
// 指路文案**恒为同一条短文案**（不再按触发次数逐级加长）——把同一段长文本在第二次/第三次
// 触发时再念一遍，不提供任何新信息，只让 AI 在被打断时读更多字（Issue #352 第四刀）。
function enhanceBlock(st, message, ruleKey, toolName) {
  const key = ruleKey || extractRuleKey(message);
  const guide = GUIDE_MAP[key] || '';
  const parts = [message];
  if (guide)
    parts.push('\n【门禁指路】' + guide + (toolName ? '（当前操作：' + toolName + '）' : ''));
  return new Error(parts.join(''));
}

