// ==================== 直连调用归一化（Issue #382 第 10 轮评审 CR10-1） ====================
// DECISION-1 后，校对 4 个纯 TS 工具**直连可调**（不再必须走网关）⇒ 而 P1~P4 校对门禁此前
// **只写在 `wps_office_execute` 分支里** ⇒ 直连调用会**整体绕过**校对治理（覆盖全文门禁 / 替换前置 /
// 进度真实性 / 批次推进全部失守）。本函数把「直连工具调用」归一成与网关调用**同一形状**
// `{ toolName, innerArgs }`，使下游 P 规则对两条通道**只有一份实现**（同一语义不写两遍）。
//
// 归一化口径（唯一定义者）：
//   · 网关调用 `wps_office_execute({ tool_name: 'proofreadBasic', arguments: {...} })`
//     → toolName = `proofreadBasic`（网关短名），innerArgs = arguments；
//   · 直连调用 `wps_word_proofread_basic({...})`
//     → toolName = 去掉 `wps-office_` / `wps_` 前缀并转驼峰（`proofreadBasic`），innerArgs = args。
//   两条通道归一后 **toolName 完全一致** ⇒ 下游判据无需区分来源。
function normalizeToolCall(outerTool, args) {
  const isGateway =
    outerTool === 'wps-office_wps_office_execute' || outerTool === 'wps_office_execute';
  if (isGateway) {
    const a = args || {};
    // 网关通道：`tool_name` 是裸 COM 短名（无应用段）⇒ app 归属留给 COM_ACTION_APP 表（R1-🔴A）。
    return { isGateway: true, toolName: a.tool_name, innerArgs: a.arguments || {}, app: null };
  }
  // 直连工具：MCP 侧名为 `wps-office_wps_{word|excel|ppt|common}_xxx`（OpenCode 加 `wps-office_` 前缀）。
  // 逐段剥离两个前缀后取应用段之后的短名并转驼峰 —— 与网关侧 `tool_name` 完全同形。
  let bare = String(outerTool || '')
    .replace(/^wps-office_/, '')
    .replace(/^wps_/, '');
  // 内置名归一（Issue #395 RC-0）：`mcp-server.ts` 注册的**内置名**（`wps_get_active_document` /
  // `wps_check_connection`）**不带应用段**，被下面的 `word|excel|ppt|common` 正则判为「非工具调用」
  // ⇒ `toolName=null` ⇒ before 钩子整体跳过、after 钩子的 `docInfoFetched=true` 永不执行。
  // 而 `skills/wps-proofread/SKILL.md` 教 AI 调的**正是内置名** ⇒ SKILL 指定动作永久不满足自己的门禁
  // （实测：内建名调完 → `getDocumentParagraphs` 恒报「请先调用 getActiveDocument」）。
  // 内置名 → 工具短名映射只此一处（唯一定义者），与下方 alias 同点，下游门禁不感知名字来源。
  // ⚠️ Issue #395 评审 CR4-1：**同族须穷尽** —— SKILL 教 AI 调的内置名不止 Word 一个：
  //   `skills/wps-excel/SKILL.md:113` 教 `wps_get_active_workbook`、
  //   `skills/wps-ppt/SKILL.md:192` 教 `wps_get_active_presentation`。
  //   三者都必须在此登记，否则 Excel/PPT 的 after 钩子（设 activeWorkbookRead/activePresentationRead）
  //   永不执行 —— 与 RC-0 逐字同构，只是换了 app。新增内置工具时同步本表（或改由 mcp-server 派生）。
  const builtin = {
    get_active_document: 'getActiveDocument',
    get_active_workbook: 'getActiveWorkbook',
    get_active_presentation: 'getActivePresentation',
  };
  // 内置名的 app 归属（唯一定义者）：与上表同点登记，防「映射有了、归属又要猜」。
  const BUILTIN_APP = {
    getActiveDocument: 'word',
    getActiveWorkbook: 'excel',
    getActivePresentation: 'ppt',
  };
  if (builtin[bare]) {
    // 内置名的 app 归属（唯一的「名字里没有应用段」的直连形态）：三件内置读工具均自带归属
    // ⇒ 在此显式登记，`app` 仍取自**这一个**来源（不在 getAppType 里再猜一遍）。
    return {
      isGateway: false,
      toolName: builtin[bare],
      innerArgs: args || {},
      app: BUILTIN_APP[builtin[bare]] || null,
    };
  }
  const m = /^(word|excel|ppt|common)_(.+)$/.exec(bare);
  if (!m) return { isGateway: false, toolName: null, innerArgs: {}, app: null };
  const camel = m[2].replace(/_(.)/g, (_, c) => c.toUpperCase());
  // 别名归一：注册名 `wps_word_get_paragraphs` 的**网关短名**是 `getDocumentParagraphs`
  // （见 `gateway/index.ts` 的 `HANDLER_MAP.set('getDocumentParagraphs|wps', …)` 别名注册）——
  // 两条通道归一后必须同一个 toolName，否则 P1/P2 「取段落」门禁对直连通道失守（实测）。
  const alias = { getParagraphs: 'getDocumentParagraphs' };
  // ⚠️ Issue #399 评审 R1-🔴A：**应用段是 app 归属的权威来源**（精确、无需猜）。
  //   此前它在此处被**丢掉**，再由 `getAppType` 用关键词表反猜 ⇒ 漏项即复发。
  // ⚠️ Issue #399 评审 R4-🟡G：`common` 段是**跨 app 共用工具**（`wps_common_save` / `convert_format`
  //   等），对它们要求「某个特定 app 的已读」是错的 —— 实测在 Excel/PPT 上下文里 `save` 被要求先
  //   `getActiveDocument`（Word），属与本次 Issue 同类的**误拦**。故 app 归属登记为 `common`
  //   （app 无关），由 G3 判据按「任一 app 已读即放行」处理（见 REQUIRES_ANY_READ）。
  const app = m[1] === 'common' ? 'common' : m[1];
  return { isGateway: false, toolName: alias[camel] || camel, innerArgs: args || {}, app: app };
}

/**
 * 校对坐标参数键名归一（Issue #395 RC-1，唯一定义者）。
 *
 * MCP schema 暴露的是 `start_offset`（`proofread.ts` 下划线），而治理层历史上按驼峰
 * `innerArgs.startOffset` 读取 ⇒ **同一套参数两套键名**：直连传 `start_offset` → 治理层报
 * 「缺少 startOffset」；传 `startOffset` → 服务端拒绝。两条通道都死。
 * 归一收敛到此处单点，两条相关门禁（proofreadBasic / getDocumentTextByRange）共用。
 */
function normalizeStartOffset(args) {
  const a = args || {};
  const v = a.startOffset !== undefined && a.startOffset !== null ? a.startOffset : a.start_offset;
  if (v === undefined || v === null || v === '') return undefined;
  const n = Number(v);
  return Number.isFinite(n) ? n : undefined;
}

