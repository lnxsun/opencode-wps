/**
 * 生成器：把 `gateway/com-actions.ts` 派生的「短名 → app」表写入
 * `.opencode/plugins/governance.js` 的登记区块（Issue #399 评审 R1-🔴A）。
 *
 * 用法：node scripts/gen-com-action-app.js [--check]
 *   · 默认：就地重写区块（BEGIN/END 标记之间）。
 *   · `--check`：只校验区块与派生表一致，不一致则退出码 1（CI 用，等价于守卫的形态判据）。
 *
 * ⚠️ 这是**派生写入**，不是「手写常量」：区块内容恒等于从注册表派生的结果，
 *   守卫 `scripts/validate-com-action-app.js` 双向断言，故不存在「两处各写一份」。
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { deriveComActionApp, renderBlock } = require('./lib/com-action-app.js');

const ROOT = path.join(__dirname, '..');
const GOV = path.join(ROOT, '.opencode', 'plugins', 'governance.js');
const BEGIN =
  '// >>> BEGIN COM_ACTION_APP (generated by scripts/gen-com-action-app.js — DO NOT EDIT)';
const END = '// <<< END COM_ACTION_APP';

function build() {
  const { byName, count, error } = deriveComActionApp(ROOT);
  if (!byName) {
    console.error(`❌ 派生失败：${error}`);
    process.exit(1);
  }
  if (count === 0) {
    console.error('❌ 派生表为空（COM_ACTIONS 结构已变）—— 拒绝以空表冒充真值。');
    process.exit(1);
  }
  return `${BEGIN}\nconst COM_ACTION_APP = {\n${renderBlock(byName)}\n};\n${END}`;
}

function main() {
  const want = build();
  const src = fs.readFileSync(GOV, 'utf8');
  const re = new RegExp(
    BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') +
      '[\\s\\S]*?' +
      END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  );
  const m = src.match(re);
  if (!m) {
    console.error('❌ governance.js 未找到 COM_ACTION_APP 登记区块（BEGIN/END 标记缺失）。');
    process.exit(1);
  }
  if (process.argv.includes('--check')) {
    if (m[0] !== want) {
      console.error(
        '❌ COM_ACTION_APP 区块与注册表派生结果不一致 —— 请运行 node scripts/gen-com-action-app.js'
      );
      process.exit(1);
    }
    console.log(
      `✅ COM_ACTION_APP 区块与注册表派生结果一致（${Object.keys(JSON.parse('{}')).length}）。`
    );
    return;
  }
  fs.writeFileSync(GOV, src.replace(re, want), 'utf8');
  console.log('✅ 已重写 COM_ACTION_APP 区块。');
}

main();
module.exports = { build };
